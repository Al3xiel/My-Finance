import com.al3xiel.my_finances.ui.theme.MyfinancesTheme

/** Estado vacío: icono decorativo opcional, texto y, si hay, una acción en píldora tonal. */
@Composable
fun EmptyState(
    title: String,
    body: String,
    modifier: Modifier = Modifier,
    actionLabel: String? = null,
    onAction: (() -> Unit)? = null,
    @DrawableRes icon: Int? = null,
) {
    Column(
        modifier = modifier.fillMaxSize().padding(32.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp, Alignment.CenterVertically),
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        icon?.let { IconBadge(it, size = 64.dp) }
        Text(text = title, style = MaterialTheme.typography.titleMedium, textAlign = TextAlign.Center)
        Text(
            text = body,
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center,
        )
        if (actionLabel != null && onAction != null) {
            PillButton(text = actionLabel, onClick = onAction, style = PillStyle.TONAL)
        }
    }
}

@Preview(showBackground = true)
@Preview(showBackground = true, uiMode = android.content.res.Configuration.UI_MODE_NIGHT_YES)
@Composable
private fun EmptyStatePreview() {
    MyfinancesTheme {
        EmptyState(title = "Aún no hay nada aquí", body = "Esta sección se activará pronto.", actionLabel = "Crear", onAction = {}, icon = AppIcons.Add)
    }
}
